price1 = 34.9
price2 = -11.1111
price3 = 111.229101
price4 = 11.2
price5 = 877.112
price6 = -2992

print(f"Price 1 : $ {price1:.3f}") # decimal point to 3
print(f"Price 2 : $ {price2:10}") # upto 10 spaces(filled with whitespace)
print(f"Price 3 : $ {price3:10.2f}") # upto 10 spaces with 2 decimal points
print(f"Price 4 : $ {price4:010}") # upto 10 spaces(filled with 0s)
print(f"Price 5 : $ {price5:<10}") # left justified with 10 whitespaces
print(f"Price 6 : $ {price6:^10}") # center justified